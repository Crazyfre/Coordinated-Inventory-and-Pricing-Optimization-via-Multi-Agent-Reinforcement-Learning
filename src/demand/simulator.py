"""P1 task 4: calibrated, controlled-elasticity stochastic demand simulator.

The pricing track's core deliverable (plans P1, Doc 4.4-4.5). Pure demand
sampling — no inventory, no lead times. Implements the env's demand-source
callable contract:  simulator(day) -> demand vector (n_skus,).
Prices are pushed in by the environment via `set_current_price`.

Model per SKU i, environment day t (Doc 4.4 with the 4.5 discipline applied):

    log(mu_it) = b0'_i
               + e_i * log(p_it / p_base_i)     <- CONTROLLED elasticity e_i
               + b_x_i^T x_t                     <- calendar coefs from NB fit
               + (L z)_i * sigma_i               <- correlated latent shock

    D_it ~ NegBin(mean = mu_it, dispersion = phi_i)   [gamma-Poisson mixture]

Design rules:
  - e_i is the CONTROLLED elasticity slider (default locked config: -1.5).
    The fitted observational beta_p values are NEVER used here (Doc 4.5:
    they are confounded — empirically several are positive).
  - b0'_i = b0_i + b_h_i . E[H] folds the GLM's history coefficients' average
    contribution into the intercept. The history term is deliberately NOT a
    self-feedback loop: in M5, "sales history" reflects past availability and
    promotions, not exogenous demand dynamics; a self-exciting term is
    structurally unstable when history is generated by the simulator itself
    (verified empirically: heavy-tail NB samples ratchet mu). Demand given
    price + calendar is therefore exogenous — stable and unbiased.
  - The residual-correlation matrix from calibration drives the latent shock
    (S5 knob via shock_std; 0 disables correlation).
  - mu is clamped to [10%, 5x] of each SKU's actual M5 average — a numerical
    guard, not a modelling assumption.

Scenario knobs: elasticity (S4), shock_std (S3/S5), phi via nb_params (S3),
episode day mapping into the M5 calendar (S2).
"""
from __future__ import annotations

import numpy as np

from src.config.locked_config import get_locked_config
from src.demand.alignment import EVENT_TYPES, build_aligned_dataset
from src.demand.calibration import load_nb_params


class CalibratedDemandSimulator:
    """Price-sensitive NB demand generator, calibrated on the locked 10 SKUs."""

    CALENDAR_COLS = (
        [f"dow_{w}" for w in range(2, 8)]
        + [f"month_{m}" for m in range(2, 13)]
        + ["snap", "is_event", "year_idx"]
        + [f"event_{t.lower()}" for t in EVENT_TYPES]
    )

    def __init__(
        self,
        nb_params: dict | None = None,
        elasticity: np.ndarray | float | None = None,
        shock_std: np.ndarray | float = 0.10,
        start_day_index: int = 1,
        aligned=None,
        rng: np.random.Generator | None = None,
        base_prices: np.ndarray | None = None,
    ):
        cfg = get_locked_config()
        self.n = cfg.env.n_skus
        params = nb_params or load_nb_params()
        self.series_ids = list(params["series_order"])
        skus = params["skus"]

        if aligned is None:
            aligned = build_aligned_dataset()

        # --- coefficients from the calibration (price coef NOT used: slider) ---
        self.b0 = np.array([skus[s]["params"]["const"] for s in self.series_ids])
        self.b_cal = np.array(
            [[skus[s]["params"][c] for c in self.CALENDAR_COLS] for s in self.series_ids]
        )
        b_hist = np.array(
            [[skus[s]["params"][c] for c in ("hist_7", "hist_28")] for s in self.series_ids]
        )
        self.phi = np.array([skus[s]["phi"] for s in self.series_ids])

        # Fold the average history contribution into the intercept:
        # b0' = b0 + b_h . E[H], E[H] from the aligned table's TRUE history.
        g = aligned.df.groupby("series_id")[["hist_7", "hist_28"]].mean()
        mean_hist = np.array([[g.loc[s, "hist_7"], g.loc[s, "hist_28"]] for s in self.series_ids])
        self.b0 = self.b0 + (b_hist * mean_hist).sum(axis=1)

        # --- controlled elasticity slider (S4 knob) — the ONLY price mechanism ---
        if elasticity is None:
            self.elasticity = np.full(self.n, cfg.demand.base_elasticity)
        else:
            self.elasticity = np.broadcast_to(
                np.asarray(elasticity, dtype=float), (self.n,)
            ).copy()

        # --- correlated latent shock (S3/S5 knobs) ---
        self.shock_std = np.broadcast_to(
            np.asarray(shock_std, dtype=float), (self.n,)
        ).copy()
        R = np.asarray(params["residual_correlation"]["matrix"], dtype=float)
        R = R + np.eye(self.n) * 1e-8  # PSD jitter for Cholesky
        self.L = np.linalg.cholesky(R)

        # --- calendar features per M5 day + level anchors ---
        first = aligned.df[aligned.df.series_id == self.series_ids[0]].sort_values("day_index")
        self.calendar_feats = first[self.CALENDAR_COLS].to_numpy(float)  # (1941, k)
        self.y_panel = aligned.df.pivot(
            index="day_index", columns="series_id", values="y"
        )[self.series_ids].to_numpy(float)  # (1941, n)
        self.level_anchor = np.maximum(self.y_panel.mean(axis=0), 0.5)

        self.start_day_index = int(start_day_index)
        self.rng = rng or np.random.default_rng()
        self._base_price_override = (
            None if base_prices is None else np.asarray(base_prices, dtype=float).copy()
        )
        self.base_prices = None
        self._price: np.ndarray | None = None
        self._env_day = 0
        self._last_mu: np.ndarray | None = None  # diagnostic handle

    # ------------------------------------------------------------------ contract

    def reset(self, rng: np.random.Generator | None = None,
              start_day_index: int | None = None) -> None:
        if rng is not None:
            self.rng = rng
        if start_day_index is not None:
            self.start_day_index = int(start_day_index)
        self._env_day = 0

    def set_current_price(self, prices: np.ndarray) -> None:
        """Env pushes the current absolute price vector (integration seam)."""
        self._price = np.asarray(prices, dtype=float).copy()

    def __call__(self, day: int) -> np.ndarray:
        if self._price is None:
            raise ValueError("set_current_price() must be called before sampling")
        self._env_day = day

        # Map env day -> M5 calendar day (cycles within the calendar horizon).
        horizon = self.calendar_feats.shape[0]
        m5_day = ((self.start_day_index + day - 2) % horizon) + 1
        x = self.calendar_feats[m5_day - 1]  # (k_cal,)

        log_mu = (
            self.b0
            + self.elasticity * np.log(np.maximum(self._price, 1e-6)
                                       / self._base_price_vector())
            + self.b_cal @ x
        )
        if self.shock_std.any():
            z = self.rng.standard_normal(self.n)
            log_mu = log_mu + self.L @ (self.shock_std * z)
        mu = np.exp(np.clip(log_mu, -5.0, 8.0))
        mu = np.clip(mu, 0.1 * self.level_anchor, 5.0 * self.level_anchor)
        self._last_mu = mu.copy()

        # NegBin(mu, phi) via gamma-Poisson mixture (vectorised, seeded).
        gamma = self.rng.gamma(shape=self.phi, scale=mu / self.phi)
        demand = self.rng.poisson(gamma).astype(float)
        return demand

    # ------------------------------------------------------------------ helpers

    def _base_price_vector(self) -> np.ndarray:
        if self._base_price_override is not None:
            return self._base_price_override
        if self.base_prices is None:
            from src.config.sku_config import load_skus

            skus = {s.series_id: s for s in load_skus()}
            self.base_prices = np.array([skus[s].base_price for s in self.series_ids])
        return self.base_prices

    def current_mu(self) -> np.ndarray:
        """Deterministic mean for the CURRENT day (for diagnostics/tests)."""
        horizon = self.calendar_feats.shape[0]
        m5_day = ((self.start_day_index + self._env_day - 2) % horizon) + 1
        x = self.calendar_feats[m5_day - 1]
        log_mu = (
            self.b0
            + self.elasticity * np.log(np.maximum(self._price, 1e-6)
                                       / self._base_price_vector())
            + self.b_cal @ x
        )
        mu = np.exp(np.clip(log_mu, -5.0, 8.0))
        return np.clip(mu, 0.1 * self.level_anchor, 5.0 * self.level_anchor)
